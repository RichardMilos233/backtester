"""
Benchmark task suite.

A task is one (ticker, date range) a search agent is dropped into. Inside the
range the data is split Train 60% / Val 20% / Test 20% exactly as before, so the
existing single-SPY experiment is just the task "SPY_full".

Tasks are what make this a benchmark rather than one experiment: a single
asset/period scores the market regime, not the agent. Scores are normalised per
task against the oracle (agent/oracle.py) and only then averaged across tasks.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional

import pandas as pd

from src.data import load_market_data


@dataclass(frozen=True)
class Task:
    task_id: str
    ticker: str
    start: Optional[str] = None     # inclusive, ISO date; None = from first bar
    end: Optional[str] = None       # inclusive; None = to last bar
    tier: str = "easy"              # easy | medium | hard, informational
    notes: str = ""

    def load(self) -> pd.DataFrame:
        df = load_market_data(self.ticker)
        if self.start:
            df = df.loc[df.index >= pd.Timestamp(self.start)]
        if self.end:
            df = df.loc[df.index <= pd.Timestamp(self.end)]
        if len(df) < 600:
            raise ValueError(f"Task {self.task_id}: only {len(df)} bars after slicing; need >= 600")
        return df

    def oracle_path(self, root) -> "Path":
        from pathlib import Path
        return Path(root) / "docs/experiments/oracle" / f"{self.task_id}.csv"


# Legacy: identical to the task every Phase 1 / Phase 2 run used.
SPY_FULL = Task("SPY_full", "SPY", tier="easy", notes="Original single-task setup; Test = 2024-05..2026-09 bull run")

# Rolling windows: Test segments land in different regimes.
#   *_w1: Test ≈ 2020-09..2021-11 (post-COVID melt-up)
#   *_w2: Test ≈ 2022-04..2023-06 (2022 bear + chop)
#   *_w3 (= full): Test ≈ 2024-05..2026-09
def _rolling(ticker: str, tier: str) -> List[Task]:
    return [
        Task(f"{ticker}_w1", ticker, "2015-01-01", "2021-11-30", tier, "Test ≈ 2020-09..2021-11"),
        Task(f"{ticker}_w2", ticker, "2016-07-01", "2023-06-30", tier, "Test ≈ 2022-02..2023-06"),
        Task(f"{ticker}_w3", ticker, None, None, tier, "Test ≈ 2024-05..latest"),
    ]


TASK_SUITE: Dict[str, List[Task]] = {
    # Trend-following friendly equity indices
    "SPY": _rolling("SPY", "easy"),
    "QQQ": _rolling("QQQ", "easy"),
    # Mean-reverting / choppy small caps and international
    "IWM": _rolling("IWM", "medium"),
    "EFA": _rolling("EFA", "medium"),
    # Non-equity: bonds (secular downtrend 2020+) and gold
    "TLT": _rolling("TLT", "medium"),
    "GLD": _rolling("GLD", "medium"),
    # Synthetic zero-drift random walk: nothing should work; tests whether an
    # agent chases noise. Generated by scripts/make_synthetic.py (fixed seed).
    "SYNTH_RW": [Task("SYNTH_RW_full", "SYNTH_RW", tier="hard", notes="zero-drift GBM, no exploitable trend")],
}

ALL_TASKS: List[Task] = [t for ts in TASK_SUITE.values() for t in ts]
TASKS_BY_ID: Dict[str, Task] = {t.task_id: t for t in ALL_TASKS}
TASKS_BY_ID[SPY_FULL.task_id] = SPY_FULL

# Smaller suites for budget-limited runs
SUITE_SMOKE = ["SPY_full"]
SUITE_CORE = ["SPY_w1", "SPY_w2", "SPY_w3", "QQQ_w2", "IWM_w2", "TLT_w3", "GLD_w1", "SYNTH_RW_full"]
SUITE_FULL = [t.task_id for t in ALL_TASKS]


def get_task(task_id: str) -> Task:
    try:
        return TASKS_BY_ID[task_id]
    except KeyError:
        raise KeyError(f"Unknown task {task_id!r}. Known: {sorted(TASKS_BY_ID)}")
